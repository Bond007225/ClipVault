// Generates golden values from the web prototype's JS core so the C++ core
// can prove it computes identical results. Run: node gen_golden.mjs > Golden.inc
import { computeShotProfile, SHOT_BASES, SHOT_RELEASES } from '../../courtlife/src/core/jumpshot.js';
import { attributeCaps } from '../../courtlife/src/core/attributes.js';
import { buildComboTimeline, DRIBBLE_MOVES } from '../../courtlife/src/core/dribble.js';
import { makeProbability, contestLevel } from '../../courtlife/src/core/shooting.js';
import { chooseFinish, finishProfile, finishMakeProbability, finishRating } from '../../courtlife/src/core/finishing.js';

const bases = Object.keys(SHOT_BASES);
const releases = Object.keys(SHOT_RELEASES);
const moves = Object.keys(DRIBBLE_MOVES);
const out = [];
const F = (v, d) => { const s = d == null ? String(v) : Number(v).toFixed(d); return (s.includes('.') ? s : s + '.0') + 'f'; };

out.push('// Generated by gen_golden.mjs from courtlife/src/core. Do not edit.');
out.push('struct ShotGolden { int base, r1, r2, blend, speed, three, vert, height; float releaseMs, greenMs, relHeight, resist; };');
out.push('static const ShotGolden kShotGolden[] = {');
let seed = 1;
const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
for (let i = 0; i < 60; i++) {
  const js = { base: bases[i % bases.length], release1: releases[(i * 3) % releases.length], release2: releases[(i * 5 + 1) % releases.length], blend: Math.round(rnd() * 100), speed: 1 + (i % 5) };
  const ctx = { threePoint: 50 + Math.round(rnd() * 49), vertical: 30 + Math.round(rnd() * 69), heightIn: 69 + Math.round(rnd() * 18) };
  const p = computeShotProfile(js, ctx);
  out.push(`  {${bases.indexOf(js.base)}, ${releases.indexOf(js.release1)}, ${releases.indexOf(js.release2)}, ${js.blend}, ${js.speed}, ${ctx.threePoint}, ${ctx.vertical}, ${ctx.heightIn}, ${F(p.releaseTimeMs)}, ${F(p.greenWindowMs)}, ${F(p.releaseHeightFt, 5)}, ${F(p.contestResist, 5)}},`);
}
out.push('};');

out.push('struct CapsGolden { int height, weight, wingspan; int caps[17]; };');
out.push('static const CapsGolden kCapsGolden[] = {');
for (const [h, w, d] of [[69, 160, -2], [75, 190, 4], [80, 225, 6], [87, 290, 8], [72, 250, 0], [84, 170, -1]]) {
  const caps = attributeCaps({ heightIn: h, weightLb: w, wingspanIn: h + d });
  out.push(`  {${h}, ${w}, ${h + d}, {${Object.values(caps).join(', ')}}},`);
}
out.push('};');

out.push('struct ComboGolden { int handle; int hand; int n; int moves[4]; float speeds[4]; float totalMs, effectiveness, offX, offZ; int endHand; };');
out.push('static const ComboGolden kComboGolden[] = {');
for (let i = 0; i < 30; i++) {
  const n = 1 + (i % 4);
  const steps = Array.from({ length: n }, (_, k) => ({ move: moves[(i * 7 + k * 3) % moves.length], speed: +(0.6 + rnd() * 0.9).toFixed(2) }));
  const handle = 40 + Math.round(rnd() * 59);
  const hand = i % 2 ? 'L' : 'R';
  const tl = buildComboTimeline({ steps }, handle, hand);
  const ms = [...steps.map((s) => moves.indexOf(s.move)), 0, 0, 0].slice(0, 4);
  const sp = [...steps.map((s) => s.speed), 1, 1, 1].slice(0, 4);
  out.push(`  {${handle}, ${hand === 'R' ? 0 : 1}, ${n}, {${ms.join(', ')}}, {${sp.map((v) => F(v)).join(', ')}}, ${F(tl.totalMs, 4)}, ${F(tl.effectiveness, 5)}, ${F(tl.offset.x, 5)}, ${F(tl.offset.z, 5)}, ${tl.endHand === 'R' ? 0 : 1}},`);
}
out.push('};');

out.push('struct MakeGolden { int grade; int rating; float dist, defDist; int defHeight; float resist, contest, prob; };');
out.push('static const MakeGolden kMakeGolden[] = {');
const grades = ['green', 'slightly-early', 'slightly-late', 'early', 'late'];
for (let i = 0; i < 40; i++) {
  const g = i % 5;
  const rating = 40 + Math.round(rnd() * 59);
  const dist = +(3 + rnd() * 27).toFixed(2);
  const defDist = i % 7 === 0 ? -1 : +(1 + rnd() * 8).toFixed(2);
  const defH = 72 + Math.round(rnd() * 14);
  const resist = +rnd().toFixed(3);
  const contest = contestLevel(defDist < 0 ? null : defDist, defH, resist);
  const prob = makeProbability({ grade: grades[g], rating, distanceFt: dist, contest });
  out.push(`  {${g}, ${rating}, ${F(dist)}, ${F(defDist)}, ${defH}, ${F(resist)}, ${F(contest, 6)}, ${F(prob, 6)}},`);
}
out.push('};');

// Finishing: finish choice, timing profile, rating and make odds.
out.push('struct FinishGolden { float dist, speed; int closeShot, layup, dunk, vert, height; int type; int rating; float gatherMs, durationMs, releaseMs, greenMs, jumpFt, relHeight, resist, defDist; int defHeight; float contest, prob; };');
out.push('static const FinishGolden kFinishGolden[] = {');
const finishTypes = [null, 'layup', 'dunk'];
for (let i = 0; i < 60; i++) {
  const dist = +(rnd() * 11).toFixed(2);
  const speed = i % 6 === 0 ? 0 : +(rnd() * 16).toFixed(2);
  const attrs = { closeShot: 40 + Math.round(rnd() * 59), drivingLayup: 40 + Math.round(rnd() * 59), drivingDunk: 30 + Math.round(rnd() * 69), vertical: 30 + Math.round(rnd() * 69) };
  const heightIn = 69 + Math.round(rnd() * 18);
  const type = chooseFinish({ distanceFt: dist, speedFtPerSec: speed, attrs, heightIn });
  // Profile/odds are checked even for jumper-range spots (as a layup) so every row exercises the math.
  const asType = type ?? 'layup';
  const rating = finishRating(attrs, asType, dist);
  const p = finishProfile(asType, { rating, vertical: attrs.vertical, heightIn, distanceFt: dist });
  const defDist = i % 5 === 0 ? -1 : +(1 + rnd() * 7).toFixed(2);
  const defH = 72 + Math.round(rnd() * 14);
  const contest = contestLevel(defDist < 0 ? null : defDist, defH, p.contestResist);
  const prob = finishMakeProbability({ type: asType, rating, contest, distanceFt: dist });
  out.push(`  {${F(dist)}, ${F(speed)}, ${attrs.closeShot}, ${attrs.drivingLayup}, ${attrs.drivingDunk}, ${attrs.vertical}, ${heightIn}, ${finishTypes.indexOf(type)}, ${rating}, ${F(p.gatherMs)}, ${F(p.durationMs)}, ${F(p.releaseTimeMs)}, ${F(p.greenWindowMs)}, ${F(p.jumpFt, 6)}, ${F(p.releaseHeightFt, 6)}, ${F(p.contestResist, 6)}, ${F(defDist)}, ${defH}, ${F(contest, 6)}, ${F(prob, 6)}},`);
}
out.push('};');
console.log(out.join('\n'));
